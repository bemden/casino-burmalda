void Story::dealerSlip() {
    UI::dialogue(
        "ОГОВОРКА ДИЛЕРА",
        "Набрав 500 морковок, ты между делом спрашиваешь дилера про Золотой "
        "Жетон. Он улыбается: «Жетон? Его сейчас у Дона нет... То есть я "
        "хотел сказать — ничего не знаю». Похоже, он знает больше, чем "
        "говорит. Надо присмотреться к нему за игровыми столами.");
}

void Story::minigameClue(int minigame) {
    const char* clues[] = {
        "После выигрыша в слотах ты замечаешь за автоматом квитанцию с "
        "инициалами дилера и номером его смены.",
        "После победы в блэкджеке тебе выдают фишку с тем же редким клеймом, "
        "что стоит на личном жетоне дилера.",
        "После выигрыша на скачках находишь записку: дилер просил букмекера "
        "передать ему весть, если кто-то спросит о Золотом Жетоне.",
        "После выигрыша в костях под столом обнаруживаешь черновик с "
        "наброском хранилища и подписью дилера."
    };
    if (minigame < 0 || minigame >= 4) return;
    UI::dialogue("НОВАЯ ЗАЦЕПКА", clues[minigame]);
}

